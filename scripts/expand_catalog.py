def sp(common, slug, sci, cat, tags, traits, scale, ar, ranges, notes):
    return {
        "common_name": common,
        "slug": slug,
        "scientific_name": sci,
        "category": cat,
        "habitat_tags": tags,
        "key_visual_traits": traits,
        "relative_scale_index": scale,
        "enabled": True,
        "notes": notes,
        "target_aspect_ratio": ar,
        "geographic_range": ranges,
    }


def prof(wt, depth, flow, veg, clarity):
    return {
        "water_type": wt,
        "depth": depth,
        "flow": flow,
        "vegetation": veg,
        "clarity": clarity,
    }


