def main() -> None:
    existing_species = json.load(open(SPECIES_PATH))
    existing_slugs = {sp["slug"] for sp in existing_species}
    existing_profiles = json.load(open(PROFILES_PATH))

    added = 0
    for s in new_species:
        if s["slug"] not in existing_slugs:
            existing_species.append(s)
            existing_slugs.add(s["slug"])
            added += 1
    for slug, profile in new_profiles.items():
        if slug not in existing_profiles:
            existing_profiles[slug] = profile

    with open(SPECIES_PATH, "w") as f:
        json.dump(existing_species, f, indent=2)
    with open(PROFILES_PATH, "w") as f:
        json.dump(existing_profiles, f, indent=2)

    print(f"Added {added} new species. Total: {len(existing_species)}")

    # Verify every species has a matching profile
    missing = [s["slug"] for s in existing_species if s["slug"] not in existing_profiles]
    if missing:
        print(f"WARNING: {len(missing)} species missing profiles: {missing[:5]}")
    else:
        print("OK: every species has a matching habitat profile.")

    # Category breakdown
    cats: dict[str, int] = {}
    for s in existing_species:
        cats[s["category"]] = cats.get(s["category"], 0) + 1
    print("Category breakdown:")
    for c, n in sorted(cats.items(), key=lambda x: -x[1]):
        print(f"  {c}: {n}")


if __name__ == "__main__":
    main()
